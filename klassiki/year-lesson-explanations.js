/* Разборы открываются по запросу ученика. Существующее задание остаётся отдельной проверкой. */
window.klassikiRenderYearExplanation=function(subjectId,lessonNumber){
 const entry=window.KlassikiYearExplanations[subjectId]?.[lessonNumber];
 if(!entry)return '';
 const [goal,theory,[prompt,...steps],exercises]=entry;
 return '<section><p><strong>Цель урока.</strong> '+esc(goal)+'</p><h3>Как это работает</h3><p>'+esc(theory)+'</p>'+
  '<h3>Разобранный пример</h3><p>'+esc(prompt)+'</p><details class="question"><summary>Разбор по шагам</summary><ol>'+
  steps.map(step=>'<li>'+esc(step)+'</li>').join('')+'</ol></details>'+
  '<h3>Самостоятельная практика</h3><ol>'+exercises.map(([task,solution])=>
   '<li><p>'+esc(task)+'</p><details class="question"><summary>Проверить решение</summary><p>'+esc(solution)+'</p></details></li>').join('')+
  '</ol></section>';
};
